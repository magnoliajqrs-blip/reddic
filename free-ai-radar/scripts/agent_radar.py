#!/usr/bin/env python3
"""agent_radar.py - live GitHub snapshot for the agent / gateway repos in ../data/agent_repos.json.

Why: "how many stars / is it still alive / what licence" changes every week, so the
report should never hard-code it. Run this script (2 minutes, ~75 API calls) and it
rewrites ../data/agents-live.json plus the generated table in ../AGENTS.md.

Usage:
    python3 scripts/agent_radar.py                # token from GITHUB_TOKEN or `gh auth token`
    python3 scripts/agent_radar.py --no-md        # JSON only

Exit codes: 0 ok, 1 no token, 2 nothing fetched.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "data" / "agent_repos.json"
OUT_JSON = ROOT / "data" / "agents-live.json"
OUT_MD = ROOT / "AGENTS.md"
API = "https://api.github.com/repos/"


def get_token() -> str | None:
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok:
        return tok.strip()
    try:
        return subprocess.check_output(["gh", "auth", "token"], text=True).strip()
    except Exception:
        return None


def fetch(repo: str, token: str | None) -> dict:
    req = urllib.request.Request(API + repo, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "free-ai-radar/1.0",
        **({"Authorization": f"Bearer {token}"} if token else {}),
    })
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            d = json.load(r)
        lic = (d.get("license") or {}).get("spdx_id") or "-"
        if lic == "NOASSERTION":
            lic = "custom"
        return {
            "repo": repo,
            "full_name": d["full_name"],
            "stars": d["stargazers_count"],
            "forks": d["forks_count"],
            "open_issues": d["open_issues_count"],
            "language": d.get("language") or "-",
            "license": lic,
            "pushed_at": d["pushed_at"],
            "archived": bool(d.get("archived")),
            "description": (d.get("description") or "").strip(),
        }
    except urllib.error.HTTPError as e:
        return {"repo": repo, "error": f"HTTP {e.code}"}
    except Exception as e:  # noqa: BLE001 - keep the scan alive
        return {"repo": repo, "error": str(e)}


def ago(iso: str) -> str:
    if not iso:
        return "-"
    t = datetime.fromisoformat(iso.replace("Z", "+00:00"))
    days = (datetime.now(timezone.utc) - t).days
    if days == 0:
        return "today"
    if days < 60:
        return f"{days}d"
    return f"{days // 30}mo"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-md", action="store_true")
    args = ap.parse_args()

    token = get_token()
    if not token:
        print("warning: no GITHUB_TOKEN / gh token - unauthenticated limit is 60 req/h",
              file=sys.stderr)

    seed = json.loads(SEED.read_text())
    meta = {r["repo"].lower(): r for r in seed["repos"]}
    repos = [r["repo"] for r in seed["repos"]]

    with ThreadPoolExecutor(max_workers=8) as pool:
        rows = list(pool.map(lambda r: fetch(r, token), repos))

    for r in rows:
        s = meta.get(r["repo"].lower(), {})
        r["category"] = s.get("category", "other")
        r["note"] = s.get("note", "")
    rows.sort(key=lambda r: r.get("stars", -1), reverse=True)

    ok = [r for r in rows if "error" not in r]
    if not ok:
        print("error: every lookup failed (token? network?)", file=sys.stderr)
        return 2

    payload = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "count_ok": len(ok),
        "count_failed": len(rows) - len(ok),
        "total_stars": sum(r["stars"] for r in ok),
        "repos": rows,
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n")

    if not args.no_md:
        lines = [
            "<!-- generated by scripts/agent_radar.py - do not edit by hand -->",
            f"# Agent radar - live GitHub snapshot ({payload['generated_at']})",
            "",
            f"{len(ok)}/{len(rows)} repos resolved · {payload['total_stars']:,} stars combined.",
            "",
            "| # | Repo | Stars | Forks | Lang | Licence | Last push | Category |",
            "|---|------|------:|------:|------|---------|-----------|----------|",
        ]
        for i, r in enumerate(ok, 1):
            lines.append(
                f"| {i} | [{r['full_name']}](https://github.com/{r['full_name']}) | "
                f"{r['stars']:,} | {r['forks']:,} | {r['language']} | {r['license']} | "
                f"{ago(r['pushed_at'])} | {r['category']} |"
            )
        failed = [r for r in rows if "error" in r]
        if failed:
            lines += ["", "Not resolved: " + ", ".join(f"`{r['repo']}` ({r['error']})" for r in failed)]
        OUT_MD.write_text("\n".join(lines) + "\n")

    print(f"wrote {OUT_JSON.relative_to(ROOT)} ({len(ok)} repos, {payload['total_stars']:,} stars)")
    if not args.no_md:
        print(f"wrote {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
