#!/usr/bin/env python3
"""render_tables.py - turn data/*.json into PROVIDERS.md (and a count summary).

Keeps the human-readable tables and the machine-readable JSON in sync: edit the JSON,
re-run this, commit both.

    python3 scripts/render_tables.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "PROVIDERS.md"

LABEL = {
    "lab": "Frontier labs (own models)",
    "inference": "Inference / GPU clouds",
    "gateway": "Gateways & aggregators (many labs, one key)",
    "agent-gateway": "Coding-agent gateways (free model promos)",
    "lab-gateway": "Lab + gateway hybrids",
    "keyless": "Keyless / no-signup endpoints",
}


def esc(s: str) -> str:
    return str(s).replace("|", "\\|")


def inject_top15(n: int = 15) -> None:
    """Rewrite the table between <!-- TOP15:START --> and <!-- TOP15:END --> in README.md."""
    live = ROOT / "data" / "agents-live.json"
    readme = ROOT / "README.md"
    if not live.exists() or not readme.exists():
        return
    data = json.loads(live.read_text())
    table = ["| # | Repo | Stars | Licence | Category |", "|---:|---|---:|---|---|"]
    for i, r in enumerate(data["repos"][:n], 1):
        table.append(
            f"| {i} | [{r['full_name']}](https://github.com/{r['full_name']}) | "
            f"{r['stars']:,} | {r['license']} | {r['category']} |"
        )
    text = readme.read_text()
    start, end = "<!-- TOP15:START -->", "<!-- TOP15:END -->"
    if start in text and end in text:
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        readme.write_text(head + start + "\n" + "\n".join(table) + "\n" + end + tail)
        print(f"refreshed top-{n} table in README.md ({data['generated_at']})")


def main() -> int:
    spec = json.loads((ROOT / "data" / "providers.json").read_text())
    rows = spec["providers"]
    by_type = Counter(p["type"] for p in rows)
    free_now = sum(1 for p in rows if not p["trial_only"])
    card_free = sum(1 for p in rows if not p["card_required"])
    compat = sum(1 for p in rows if p["openai_compatible"])

    lines = [
        "<!-- generated by scripts/render_tables.py - edit data/providers.json instead -->",
        f"# Free LLM API providers - snapshot {spec['as_of']}",
        "",
        f"- **{len(rows)} providers** tracked · **{free_now}** with a standing (non-trial) free tier · "
        f"**{card_free}** need no credit card · **{compat}** speak the OpenAI Chat Completions shape.",
        "- " + spec["caveat"],
        "",
    ]
    order = ["inference", "lab", "gateway", "agent-gateway", "lab-gateway", "keyless"]
    for t in order:
        group = [p for p in rows if p["type"] == t]
        if not group:
            continue
        lines += [
            f"## {LABEL.get(t, t)} ({len(group)})",
            "",
            "| Provider | Free models | Free limits | Card | Base URL | Env var | Key page |",
            "|----------|-------------|-------------|:----:|----------|---------|----------|",
        ]
        for p in sorted(group, key=lambda x: x["company"].lower()):
            card = "yes" if p["card_required"] else "no"
            trial = " _(trial)_" if p["trial_only"] else ""
            lines.append(
                f"| **{esc(p['company'])}**{trial} | {esc(p['free_models'])} | {esc(p['free_limits'])} | "
                f"{card} | `{esc(p['base_url'])}` | `{p['key_env']}` | {p['signup']} |"
            )
        lines.append("")

    lines += [
        "## Types at a glance",
        "",
        "| Type | Count |",
        "|------|------:|",
        *[f"| {LABEL.get(k, k)} | {v} |" for k, v in by_type.most_common()],
        "",
        "## Notes that bite in practice",
        "",
        "1. **Per-project, not per-key.** Gemini and several gateways count limits per project/account, "
        "so minting more keys does not buy more quota.",
        "2. **Promo models rotate.** `:free` / FREE SKUs (OpenRouter, OpenCode Zen, Nous, Kilo, Cline) "
        "disappear without notice - never hard-code a free model id in production.",
        "3. **Free tier often means data training.** Google's free tier says content may be used to "
        "improve products; GitHub Models uses Microsoft data terms; most $0 gateways log prompts.",
        "4. **TPM beats RPM.** 30 RPM with 8k TPM is ~4 average replies per minute - the token cap "
        "is the real ceiling.",
        "5. **Trial credits are not a free tier.** Anything tagged _(trial)_ expires; keep it out of "
        "your critical path.",
        "",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.name}: {len(rows)} providers")
    inject_top15()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
